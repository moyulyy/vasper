_cache: dict[tuple[str, str, int, float], QPixmap] = {}


def pixmap(name: str, color: str, size: int = 18, stroke: float = 1.8) -> QPixmap:
    key = (name, color, size, stroke)
    cached = _cache.get(key)
    if cached is not None:
        return cached
    body = _ICONS.get(name, _ICONS["circle-dot"]).replace("CUR", color)
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
        f'stroke="{color}" stroke-width="{stroke}" stroke-linecap="round" '
        f'stroke-linejoin="round">{body}</svg>'
    )
    renderer = QSvgRenderer(QByteArray(svg.encode("utf-8")))
    ratio = 2
    result = QPixmap(size * ratio, size * ratio)
    result.setDevicePixelRatio(ratio)
    result.fill(Qt.GlobalColor.transparent)
    painter = QPainter(result)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)
    renderer.render(painter, QRectF(0, 0, size, size))
    painter.end()
    _cache[key] = result
    return result


def icon(name: str, color: str, size: int = 18, stroke: float = 1.8) -> QIcon:
    return QIcon(pixmap(name, color, size, stroke))


def clear_cache() -> None:
    _cache.clear()
